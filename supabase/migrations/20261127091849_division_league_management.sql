-- Division league structure, promotion/relegation rules and auditable club movements.
-- Additive only: existing competitions, clubs, standings, fixtures and results are not rewritten.

create table if not exists public.league_division_settings (
  id bigint generated by default as identity primary key,
  league_id bigint not null references public.leagues(id) on delete cascade,
  season_id bigint not null references public.seasons(id) on delete restrict,
  tier_code text not null check (tier_code in ('PREMIER','DIVISION_1','DIVISION_2','DIVISION_3','REGIONAL','YOUTH','OTHER')),
  tier_rank integer not null check (tier_rank between 1 and 20),
  pyramid_group text not null check (pyramid_group in ('MEN','WOMEN','YOUTH','REGIONAL','OPEN')),
  promotion_spots integer not null default 0 check (promotion_spots between 0 and 30),
  relegation_spots integer not null default 0 check (relegation_spots between 0 and 30),
  playoff_spots integer not null default 0 check (playoff_spots between 0 and 30),
  promotion_playoff boolean not null default false,
  relegation_playoff boolean not null default false,
  movement_policy text not null default 'MANUAL_APPROVAL'
    check (movement_policy in ('MANUAL_APPROVAL','APPROVAL_REQUIRED')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint league_division_settings_league_season_key unique (league_id, season_id)
);

create index if not exists league_division_settings_group_rank_idx
  on public.league_division_settings (season_id, pyramid_group, tier_rank);

alter table public.league_division_settings enable row level security;
drop policy if exists league_division_settings_public_read on public.league_division_settings;
create policy league_division_settings_public_read
  on public.league_division_settings for select to anon, authenticated using (true);
drop policy if exists league_division_settings_super_admin_manage on public.league_division_settings;
create policy league_division_settings_super_admin_manage
  on public.league_division_settings for all to authenticated
  using (public.app_role() = 'SUPER_ADMIN')
  with check (public.app_role() = 'SUPER_ADMIN');

revoke all on public.league_division_settings from anon;
revoke all on public.league_division_settings from authenticated;
grant select on public.league_division_settings to anon, authenticated;
grant insert, update, delete on public.league_division_settings to authenticated;
revoke all on sequence public.league_division_settings_id_seq from anon, authenticated;
grant usage, select on sequence public.league_division_settings_id_seq to authenticated;

create table if not exists public.league_movement_records (
  id bigint generated by default as identity primary key,
  season_id bigint not null references public.seasons(id) on delete restrict,
  club_id uuid not null references public.league_clubs(id) on delete restrict,
  from_league_id bigint not null references public.leagues(id) on delete restrict,
  to_league_id bigint not null references public.leagues(id) on delete restrict,
  movement_type text not null check (movement_type in ('PROMOTION','RELEGATION','PLAYOFF','TRANSFER')),
  decision_status text not null default 'APPROVED'
    check (decision_status in ('APPROVED','REJECTED','APPLIED')),
  reason text not null check (length(trim(reason)) between 5 and 1000),
  created_by uuid not null default auth.uid() references auth.users(id),
  approved_by uuid not null default auth.uid() references auth.users(id),
  applied_at timestamptz,
  created_at timestamptz not null default now(),
  constraint league_movement_different_competitions check (from_league_id <> to_league_id)
);

create index if not exists league_movement_records_season_idx
  on public.league_movement_records (season_id, created_at desc);
create index if not exists league_movement_records_club_idx
  on public.league_movement_records (club_id, created_at desc);

alter table public.league_movement_records enable row level security;
drop policy if exists league_movement_records_public_read on public.league_movement_records;
create policy league_movement_records_public_read
  on public.league_movement_records for select to anon, authenticated
  using (decision_status = 'APPLIED');
drop policy if exists league_movement_records_super_admin_manage on public.league_movement_records;
create policy league_movement_records_super_admin_manage
  on public.league_movement_records for all to authenticated
  using (public.app_role() = 'SUPER_ADMIN')
  with check (public.app_role() = 'SUPER_ADMIN');

revoke all on public.league_movement_records from anon;
revoke all on public.league_movement_records from authenticated;
grant select on public.league_movement_records to anon, authenticated;
grant insert, update, delete on public.league_movement_records to authenticated;
revoke all on sequence public.league_movement_records_id_seq from anon, authenticated;
grant usage, select on sequence public.league_movement_records_id_seq to authenticated;

create or replace function public.admin_apply_league_movement(p_movement_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_move public.league_movement_records%rowtype;
  v_source public.league_division_settings%rowtype;
  v_target public.league_division_settings%rowtype;
begin
  if public.app_role() <> 'SUPER_ADMIN' then
    raise exception 'Only the Super Admin can apply a club movement.';
  end if;

  select * into v_move
    from public.league_movement_records
   where id = p_movement_id
   for update;

  if not found then
    raise exception 'The movement record does not exist.';
  end if;
  if v_move.decision_status <> 'APPROVED' then
    raise exception 'Only an approved movement can be applied.';
  end if;

  select * into v_source from public.league_division_settings
   where league_id = v_move.from_league_id and season_id = v_move.season_id;
  if not found then
    raise exception 'The source competition has no division settings for this season.';
  end if;

  select * into v_target from public.league_division_settings
   where league_id = v_move.to_league_id and season_id = v_move.season_id;
  if not found then
    raise exception 'The destination competition has no division settings for this season.';
  end if;

  if v_source.pyramid_group <> v_target.pyramid_group then
    raise exception 'A club cannot move between different competition pyramids.';
  end if;

  if v_move.movement_type = 'PROMOTION' and v_target.tier_rank >= v_source.tier_rank then
    raise exception 'Promotion must move the club to a higher division tier.';
  elsif v_move.movement_type = 'RELEGATION' and v_target.tier_rank <= v_source.tier_rank then
    raise exception 'Relegation must move the club to a lower division tier.';
  elsif v_move.movement_type = 'PLAYOFF' and abs(v_target.tier_rank - v_source.tier_rank) <> 1 then
    raise exception 'A division playoff must connect adjacent tiers.';
  end if;

  if not exists (
    select 1 from public.league_clubs
     where id = v_move.club_id and league_id = v_move.from_league_id and is_active = true
  ) then
    raise exception 'The club is not currently active in the selected source competition.';
  end if;

  if not exists (select 1 from public.leagues where id = v_move.to_league_id and is_active = true) then
    raise exception 'The destination competition is not published and active.';
  end if;

  update public.league_clubs
     set league_id = v_move.to_league_id
   where id = v_move.club_id and league_id = v_move.from_league_id;

  update public.league_movement_records
     set decision_status = 'APPLIED', applied_at = now()
   where id = p_movement_id;

  return p_movement_id;
end;
$$;

revoke all on function public.admin_apply_league_movement(bigint) from public;
revoke all on function public.admin_apply_league_movement(bigint) from anon;
grant execute on function public.admin_apply_league_movement(bigint) to authenticated;

notify pgrst, 'reload schema';
