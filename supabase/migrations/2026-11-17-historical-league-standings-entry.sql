-- Historical league table entry.
-- Keeps archived final standings separate from the live table and match-derived records.
-- Super Admins can replace one past season's table by CSV import or manual entry.
CREATE TABLE IF NOT EXISTS public.season_standings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id bigint NOT NULL REFERENCES public.seasons(id),
  league_id bigint NOT NULL REFERENCES public.leagues(id),
  pos integer NOT NULL CHECK (pos > 0),
  club text NOT NULL CHECK (char_length(trim(club)) BETWEEN 1 AND 120),
  mp integer NOT NULL DEFAULT 0 CHECK (mp >= 0),
  w integer NOT NULL DEFAULT 0 CHECK (w >= 0),
  d integer NOT NULL DEFAULT 0 CHECK (d >= 0),
  l integer NOT NULL DEFAULT 0 CHECK (l >= 0),
  gf integer NOT NULL DEFAULT 0 CHECK (gf >= 0),
  ga integer NOT NULL DEFAULT 0 CHECK (ga >= 0),
  pts integer NOT NULL DEFAULT 0 CHECK (pts >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT season_standings_matches_check CHECK (mp = w + d + l),
  CONSTRAINT season_standings_club_unique UNIQUE (season_id, league_id, club),
  CONSTRAINT season_standings_position_unique UNIQUE (season_id, league_id, pos)
);

ALTER TABLE public.season_standings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS season_standings_public_read ON public.season_standings;
CREATE POLICY season_standings_public_read
  ON public.season_standings
  FOR SELECT
  TO anon, authenticated
  USING (true);

REVOKE ALL ON TABLE public.season_standings FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.season_standings TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.admin_save_season_standings(
  p_season_id bigint,
  p_league_id bigint,
  p_rows jsonb
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_count integer;
BEGIN
  IF public.app_role() IS DISTINCT FROM 'SUPER_ADMIN' THEN
    RAISE EXCEPTION 'Only a Super Admin can save historical league standings.';
  END IF;

  IF p_season_id IS NULL OR p_league_id IS NULL THEN
    RAISE EXCEPTION 'Choose a competition and a past season.';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.seasons WHERE id = p_season_id) THEN
    RAISE EXCEPTION 'The selected season does not exist.';
  END IF;

  IF EXISTS (SELECT 1 FROM public.seasons WHERE id = p_season_id AND is_current) THEN
    RAISE EXCEPTION 'Historical standings can only be saved for a past season. The current table is calculated from match results.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.leagues
    WHERE id = p_league_id AND competition_type = 'LEAGUE'
  ) THEN
    RAISE EXCEPTION 'Choose an existing league competition.';
  END IF;

  IF jsonb_typeof(p_rows) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_rows) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'Provide between 1 and 100 club rows.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_rows) AS x(
      pos numeric, club text, mp numeric, w numeric, d numeric, l numeric,
      gf numeric, ga numeric, pts numeric
    )
    WHERE x.pos IS NULL OR x.pos <> trunc(x.pos) OR x.pos < 1
       OR x.club IS NULL OR char_length(trim(x.club)) NOT BETWEEN 1 AND 120
       OR x.mp IS NULL OR x.mp <> trunc(x.mp) OR x.mp < 0
       OR x.w IS NULL OR x.w <> trunc(x.w) OR x.w < 0
       OR x.d IS NULL OR x.d <> trunc(x.d) OR x.d < 0
       OR x.l IS NULL OR x.l <> trunc(x.l) OR x.l < 0
       OR x.gf IS NULL OR x.gf <> trunc(x.gf) OR x.gf < 0
       OR x.ga IS NULL OR x.ga <> trunc(x.ga) OR x.ga < 0
       OR x.pts IS NULL OR x.pts <> trunc(x.pts) OR x.pts < 0
       OR x.mp <> x.w + x.d + x.l
  ) THEN
    RAISE EXCEPTION 'Check every row: values must be whole non-negative numbers, position must be positive, and played must equal wins + draws + losses.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_rows) AS x(
      pos numeric, club text, mp numeric, w numeric, d numeric, l numeric,
      gf numeric, ga numeric, pts numeric
    )
    GROUP BY lower(trim(x.club))
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'A club appears more than once. Each club must have one row.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_rows) AS x(
      pos numeric, club text, mp numeric, w numeric, d numeric, l numeric,
      gf numeric, ga numeric, pts numeric
    )
    GROUP BY x.pos
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Each club must have a different league position.';
  END IF;

  v_count := jsonb_array_length(p_rows);

  -- Replace only this competition's table for this past season.
  -- Other seasons, competitions, fixtures, match scores and the live table are untouched.
  DELETE FROM public.season_standings
   WHERE season_id = p_season_id AND league_id = p_league_id;

  INSERT INTO public.season_standings (
    season_id, league_id, pos, club, mp, w, d, l, gf, ga, pts, updated_at
  )
  SELECT
    p_season_id, p_league_id, x.pos::integer, trim(x.club),
    x.mp::integer, x.w::integer, x.d::integer, x.l::integer,
    x.gf::integer, x.ga::integer, x.pts::integer, now()
  FROM jsonb_to_recordset(p_rows) AS x(
    pos numeric, club text, mp numeric, w numeric, d numeric, l numeric,
    gf numeric, ga numeric, pts numeric
  );

  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_save_season_standings(bigint, bigint, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_save_season_standings(bigint, bigint, jsonb) TO authenticated;

COMMENT ON TABLE public.season_standings IS
  'Published final league tables for past seasons; separate from the automatically calculated current league_standings table.';

NOTIFY pgrst, 'reload schema';
