-- Club profile changes are submitted by Club Managers and published only after Super Admin approval.
-- This migration intentionally does not alter existing club or squad records.

create table if not exists public.club_profile_change_requests (
  id bigint generated by default as identity primary key,
  club_id uuid not null references public.league_clubs(id) on delete cascade,
  submitted_by uuid not null references auth.users(id) on delete restrict,
  submitted_by_name text,
  proposed_profile jsonb not null,
  status text not null default 'SUBMITTED'
    check (status in ('SUBMITTED', 'APPROVED', 'RETURNED')),
  submitted_at timestamptz not null default now(),
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  review_note text
);

create unique index if not exists club_profile_one_pending_per_club
  on public.club_profile_change_requests (club_id)
  where status = 'SUBMITTED';

create index if not exists club_profile_requests_submitted_at
  on public.club_profile_change_requests (submitted_at desc);

create table if not exists public.club_profile_change_audit (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.club_profile_change_requests(id) on delete restrict,
  club_id uuid not null references public.league_clubs(id) on delete restrict,
  actor_id uuid not null references auth.users(id) on delete restrict,
  action text not null check (action in ('SUBMITTED', 'APPROVED', 'RETURNED')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.club_profile_change_requests enable row level security;
alter table public.club_profile_change_audit enable row level security;

drop policy if exists "club profile requests visible to submitter and reviewers" on public.club_profile_change_requests;
create policy "club profile requests visible to submitter and reviewers"
  on public.club_profile_change_requests for select to authenticated
  using (
    submitted_by = (select auth.uid())
    or app_role() in ('SUPER_ADMIN', 'DEVELOPER')
  );

drop policy if exists "club profile audit visible to reviewers" on public.club_profile_change_audit;
create policy "club profile audit visible to reviewers"
  on public.club_profile_change_audit for select to authenticated
  using (app_role() in ('SUPER_ADMIN', 'DEVELOPER'));

revoke all on public.club_profile_change_requests from anon, authenticated;
grant select on public.club_profile_change_requests to authenticated;
revoke all on public.club_profile_change_audit from anon, authenticated;
grant select on public.club_profile_change_audit to authenticated;

-- Block direct Club Manager edits to the live profile. Only the approval RPC can apply them.
create or replace function public.guard_club_profile_direct_update()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if app_role() = 'CLUB_ADMIN'
     and (
       new.stadium is distinct from old.stadium
       or new.city is distinct from old.city
       or new.founded_year is distinct from old.founded_year
       or new.about is distinct from old.about
     )
     and coalesce(current_setting('app.club_profile_approval', true), '') <> 'approved' then
    raise exception 'Club profile changes must be submitted for Super Admin approval.';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_club_profile_direct_update on public.league_clubs;
create trigger guard_club_profile_direct_update
  before update on public.league_clubs
  for each row execute function public.guard_club_profile_direct_update();

create or replace function public.submit_club_profile_change(
  p_stadium text,
  p_city text,
  p_founded_year integer,
  p_about text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_club uuid;
  v_name text;
  v_request_id bigint;
begin
  if v_user is null or app_role() <> 'CLUB_ADMIN' then
    raise exception 'Only an assigned Club Manager can submit club profile changes.';
  end if;

  select club_id, coalesce(full_name, email)
    into v_club, v_name
    from public.user_profiles
    where id = v_user and upper(system_role) = 'CLUB_ADMIN' and lower(status) = 'active';

  if v_club is null then
    raise exception 'Your Club Manager account is not assigned to a club.';
  end if;
  if not exists (select 1 from public.league_clubs where id = v_club and is_active = true) then
    raise exception 'Your assigned club is not active.';
  end if;
  if p_stadium is not null and length(btrim(p_stadium)) > 160 then raise exception 'Home ground must be 160 characters or fewer.'; end if;
  if p_city is not null and length(btrim(p_city)) > 120 then raise exception 'City must be 120 characters or fewer.'; end if;
  if p_about is not null and length(btrim(p_about)) > 2000 then raise exception 'Club description must be 2,000 characters or fewer.'; end if;
  if p_founded_year is not null and (p_founded_year < 1850 or p_founded_year > extract(year from now())::integer) then
    raise exception 'Enter a valid founding year.';
  end if;

  insert into public.club_profile_change_requests
    (club_id, submitted_by, submitted_by_name, proposed_profile)
  values (
    v_club, v_user, v_name,
    jsonb_build_object(
      'stadium', nullif(btrim(p_stadium), ''),
      'city', nullif(btrim(p_city), ''),
      'founded_year', p_founded_year,
      'about', nullif(btrim(p_about), '')
    )
  )
  returning id into v_request_id;

  insert into public.club_profile_change_audit (request_id, club_id, actor_id, action, details)
  values (v_request_id, v_club, v_user, 'SUBMITTED', jsonb_build_object('proposed_profile', jsonb_build_object(
    'stadium', nullif(btrim(p_stadium), ''), 'city', nullif(btrim(p_city), ''),
    'founded_year', p_founded_year, 'about', nullif(btrim(p_about), '')
  )));

  return v_request_id;
end;
$$;

create or replace function public.review_club_profile_change(
  p_request_id bigint,
  p_decision text,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.club_profile_change_requests%rowtype;
  v_profile jsonb;
  v_decision text := upper(coalesce(p_decision, ''));
  v_actor uuid := auth.uid();
begin
  if v_actor is null or app_role() <> 'SUPER_ADMIN' then
    raise exception 'Only the Super Admin can review club profile changes.';
  end if;
  if v_decision not in ('APPROVE', 'RETURN') then
    raise exception 'Choose APPROVE or RETURN.';
  end if;
  if p_note is not null and length(btrim(p_note)) > 1000 then
    raise exception 'Review note must be 1,000 characters or fewer.';
  end if;

  select * into v_request
    from public.club_profile_change_requests
    where id = p_request_id
    for update;

  if not found then raise exception 'Club profile request not found.'; end if;
  if v_request.status <> 'SUBMITTED' then raise exception 'This request has already been reviewed.'; end if;

  v_profile := v_request.proposed_profile;

  if v_decision = 'APPROVE' then
    perform set_config('app.club_profile_approval', 'approved', true);
    update public.league_clubs
      set stadium = v_profile ->> 'stadium',
          city = v_profile ->> 'city',
          founded_year = nullif(v_profile ->> 'founded_year', '')::integer,
          about = v_profile ->> 'about'
      where id = v_request.club_id;
    perform set_config('app.club_profile_approval', '', true);
    update public.club_profile_change_requests
      set status = 'APPROVED', reviewed_by = v_actor, reviewed_at = now(), review_note = nullif(btrim(p_note), '')
      where id = p_request_id;
  else
    update public.club_profile_change_requests
      set status = 'RETURNED', reviewed_by = v_actor, reviewed_at = now(), review_note = nullif(btrim(p_note), '')
      where id = p_request_id;
  end if;

  insert into public.club_profile_change_audit (request_id, club_id, actor_id, action, details)
  values (
    p_request_id, v_request.club_id, v_actor,
    case when v_decision = 'APPROVE' then 'APPROVED' else 'RETURNED' end,
    jsonb_build_object('note', nullif(btrim(p_note), ''), 'proposed_profile', v_profile)
  );
end;
$$;

revoke all on function public.submit_club_profile_change(text, text, integer, text) from public, anon;
grant execute on function public.submit_club_profile_change(text, text, integer, text) to authenticated;
revoke all on function public.review_club_profile_change(bigint, text, text) from public, anon;
grant execute on function public.review_club_profile_change(bigint, text, text) to authenticated;
