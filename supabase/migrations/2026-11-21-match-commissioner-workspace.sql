-- Match Commissioner reporting, review controls, and private evidence storage.
create table if not exists public.match_commissioner_reports (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  commissioner_user_id uuid not null references public.user_profiles(id) on delete cascade,
  report_status text not null default 'DRAFT' check (report_status in ('DRAFT','SUBMITTED','REVIEWED')),
  pitch_condition text, facilities_condition text, security_arrangements text,
  home_team_arrival text, away_team_arrival text, officials_arrival text, pre_match_notes text,
  crowd_behaviour text, match_interruptions text, match_conduct text, incident_details text,
  post_match_summary text, recommendations text,
  evidence_paths text[] not null default '{}',
  submitted_at timestamptz, reviewed_at timestamptz,
  reviewed_by uuid references public.user_profiles(id), review_notes text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint match_commissioner_reports_one_per_match unique (match_id, commissioner_user_id)
);

alter table public.match_commissioner_reports enable row level security;
revoke all on public.match_commissioner_reports from public, anon;
grant select, insert, update on public.match_commissioner_reports to authenticated;

drop policy if exists mc_reports_select_own_or_admin on public.match_commissioner_reports;
create policy mc_reports_select_own_or_admin on public.match_commissioner_reports
for select to authenticated using (commissioner_user_id = auth.uid() or app_role() in ('DEVELOPER','SUPER_ADMIN'));

drop policy if exists mc_reports_insert_assigned_commissioner on public.match_commissioner_reports;
create policy mc_reports_insert_assigned_commissioner on public.match_commissioner_reports
for insert to authenticated with check (
  commissioner_user_id = auth.uid()
  and report_status in ('DRAFT','SUBMITTED')
  and exists (select 1 from public.user_profiles p where p.id=auth.uid()
    and p.system_role='REFEREE' and lower(coalesce(p.official_title,''))='match commissioner' and lower(p.status)='active')
  and exists (select 1 from public.match_referee_assignments a where a.referee_user_id=auth.uid()
    and a.match_id=match_commissioner_reports.match_id and a.official_role='MATCH_COMMISSIONER' and a.assignment_status='ACTIVE')
);

drop policy if exists mc_reports_update_own_assigned on public.match_commissioner_reports;
create policy mc_reports_update_own_assigned on public.match_commissioner_reports
for update to authenticated
using (
  commissioner_user_id=auth.uid() and report_status <> 'REVIEWED'
  and exists (select 1 from public.user_profiles p where p.id=auth.uid()
    and p.system_role='REFEREE' and lower(coalesce(p.official_title,''))='match commissioner' and lower(p.status)='active')
  and exists (select 1 from public.match_referee_assignments a where a.referee_user_id=auth.uid()
    and a.match_id=match_commissioner_reports.match_id and a.official_role='MATCH_COMMISSIONER' and a.assignment_status='ACTIVE')
)
with check (
  commissioner_user_id=auth.uid() and report_status in ('DRAFT','SUBMITTED')
  and exists (select 1 from public.user_profiles p where p.id=auth.uid()
    and p.system_role='REFEREE' and lower(coalesce(p.official_title,''))='match commissioner' and lower(p.status)='active')
  and exists (select 1 from public.match_referee_assignments a where a.referee_user_id=auth.uid()
    and a.match_id=match_commissioner_reports.match_id and a.official_role='MATCH_COMMISSIONER' and a.assignment_status='ACTIVE')
);

drop policy if exists mc_reports_admin_update on public.match_commissioner_reports;
create policy mc_reports_admin_update on public.match_commissioner_reports
for update to authenticated using (app_role() in ('DEVELOPER','SUPER_ADMIN'))
with check (app_role() in ('DEVELOPER','SUPER_ADMIN'));

create or replace function public.guard_match_commissioner_report()
returns trigger language plpgsql set search_path=public as $$
begin
  new.updated_at := now();
  if app_role() not in ('DEVELOPER','SUPER_ADMIN') then
    if tg_op='INSERT' then
      if new.report_status not in ('DRAFT','SUBMITTED') or new.reviewed_at is not null
         or new.reviewed_by is not null or new.review_notes is not null then
        raise exception 'Commissioners may only create draft or submitted reports.';
      end if;
    else
      if new.match_id is distinct from old.match_id or new.commissioner_user_id is distinct from old.commissioner_user_id then
        raise exception 'A report cannot be reassigned to another match or commissioner.';
      end if;
      if new.report_status not in ('DRAFT','SUBMITTED') or new.reviewed_at is distinct from old.reviewed_at
         or new.reviewed_by is distinct from old.reviewed_by or new.review_notes is distinct from old.review_notes then
        raise exception 'Only the competition administrator can review a report.';
      end if;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists guard_match_commissioner_report on public.match_commissioner_reports;
create trigger guard_match_commissioner_report before insert or update on public.match_commissioner_reports
for each row execute function public.guard_match_commissioner_report();

