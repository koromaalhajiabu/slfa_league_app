drop policy if exists mc_evidence_insert_own_assignment on storage.objects;
create policy mc_evidence_insert_own_assignment on storage.objects
for insert to authenticated with check (
  bucket_id='match-commissioner-evidence'
  and (storage.foldername(name))[1]=auth.uid()::text
  and exists (select 1 from public.user_profiles p where p.id=auth.uid()
    and p.system_role='REFEREE' and lower(coalesce(p.official_title,''))='match commissioner' and lower(p.status)='active')
  and exists (select 1 from public.match_referee_assignments a where a.referee_user_id=auth.uid()
    and a.match_id::text=(storage.foldername(name))[2] and a.official_role='MATCH_COMMISSIONER' and a.assignment_status='ACTIVE')
);

drop policy if exists mc_evidence_select_own_or_admin on storage.objects;
create policy mc_evidence_select_own_or_admin on storage.objects
for select to authenticated using (
  bucket_id='match-commissioner-evidence'
  and (
    (storage.foldername(name))[1]=auth.uid()::text
    or app_role() in ('DEVELOPER','SUPER_ADMIN')
  )
);

